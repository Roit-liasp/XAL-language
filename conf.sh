#!/bin/sh
# XOS_BACKEND  posix | win | bare      (override: XOS_BACKEND=bare sh conf.sh)
# XOS_CAPS     -DXOS_HAS_*=0 switches  (override: XOS_CAPS="-DXOS_HAS_THREADS=0")

OUT="${1:-build}"
CC="${CC:-cc}"

mkdir -p "$OUT"
T="$OUT/.conf$$"

trap 'rm -f "$T.c" "$T.bin" "$T.out"' EXIT INT TERM

BACKEND="${XOS_BACKEND:-}"
if [ -z "$BACKEND" ]; then
	case "$($CC -dumpmachine 2>/dev/null)" in
		*mingw*|*windows*|*cygwin*) BACKEND=win ;;
		*none*|*elf) BACKEND=bare ;;
		*) BACKEND=posix ;;
	esac
fi

LDFLAGS=""
LINKMODE="dynamic"
XOS_LIBS=""
CAPS="${XOS_CAPS:-}"

if [ "$BACKEND" = posix ]; then
	cat > "$T.c" <<'EOC'
int main(void) { return 0; }
EOC
	if $CC -static "$T.c" -o "$T.bin" >/dev/null 2>&1; then
		LDFLAGS="-static"
		LINKMODE="static"
	fi

	cat > "$T.c" <<'EOC'
#include <pthread.h>
int main(void) { pthread_t t; (void)t; return 0; }
EOC
	if $CC -pthread "$T.c" -o "$T.bin" >/dev/null 2>&1; then
		XOS_LIBS="-pthread"
	else
		CAPS="$CAPS -DXOS_HAS_THREADS=0"
	fi
elif [ "$BACKEND" = bare ]; then
	CAPS="$CAPS -ffreestanding -DXVM_FREESTANDING -DXOS_HAS_FS=0 -DXOS_HAS_DIR=0 -DXOS_HAS_ENV=0 -DXOS_HAS_PROC=0 -DXOS_HAS_TERM=0 -DXOS_HAS_THREADS=0 -DXOS_HAS_CWD=0"
	LDFLAGS="-nostdlib -static"
fi

cat > "$OUT/config.mk" <<EOC
# Automatically generated by conf.sh - DO NOT EDIT
XOS_BACKEND = $BACKEND
XOS_CAPS = $CAPS
XOS_LIBS = $XOS_LIBS
LDFLAGS = $LDFLAGS
LINKMODE = $LINKMODE
EOC

echo "[+] xal config: backend=$BACKEND link=$LINKMODE caps='$CAPS'"
exit 0
